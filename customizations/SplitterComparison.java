import java.net.*;
import java.nio.file.*;
import java.util.*;
import java.lang.reflect.*;
import org.objectweb.asm.*;

/** Differential rebuild check: existing addon versus adopted maintainable source. */
public class SplitterComparison implements Opcodes {
 static URLClassLoader isolated(Path path,ClassLoader parent)throws Exception {
  return new URLClassLoader(new URL[]{path.toUri().toURL()},parent) {
   @Override protected Class<?> loadClass(String name,boolean resolve)throws ClassNotFoundException {
    if(!name.startsWith("emfjit."))return super.loadClass(name,resolve);
    synchronized(getClassLoadingLock(name)) {
     Class<?> found=findLoadedClass(name);if(found==null)found=findClass(name);
     if(resolve)resolveClass(found);return found;
    }
   }
  };
 }
 static byte[] model(int variant,int stores) {
  ClassWriter writer=new ClassWriter(ClassWriter.COMPUTE_MAXS);
  writer.visit(V1_8,ACC_PUBLIC,"SyntheticModel",null,"java/lang/Object",null);
  if(variant==0){writer.visitEnd();return writer.toByteArray();}
  MethodVisitor method=writer.visitMethod(ACC_PUBLIC|(variant==2?0:ACC_STATIC),"eval","([F[Z)V",null,null);
  method.visitCode();Label begin=new Label(),end=new Label(),handler=new Label();method.visitLabel(begin);
  int floats=variant==2?1:0;
  if(variant==4){Label branch=new Label();method.visitVarInsn(ALOAD,variant==2?2:1);method.visitInsn(ICONST_0);method.visitInsn(BALOAD);method.visitJumpInsn(IFEQ,branch);method.visitInsn(NOP);method.visitLabel(branch);}
  for(int i=0;i<stores;i++) {
   if(variant==6)method.visitInsn(NOP);
   else {method.visitVarInsn(ALOAD,floats);method.visitIntInsn(BIPUSH,i%16);method.visitInsn(FCONST_1);method.visitInsn(FASTORE);}
  }
  if(variant==7){Label early=new Label();method.visitVarInsn(ALOAD,1);method.visitInsn(ICONST_0);method.visitInsn(BALOAD);method.visitJumpInsn(IFEQ,early);method.visitInsn(RETURN);method.visitLabel(early);}
  method.visitLabel(end);method.visitInsn(RETURN);
  if(variant==3){method.visitLabel(handler);method.visitInsn(POP);method.visitInsn(RETURN);method.visitTryCatchBlock(begin,end,handler,"java/lang/Exception");}
  method.visitMaxs(0,0);method.visitEnd();
  if(variant==5){var previous=writer.visitMethod(ACC_PRIVATE|ACC_STATIC,"eval$0","([F[Z)V",null,null);previous.visitCode();previous.visitInsn(RETURN);previous.visitMaxs(0,0);previous.visitEnd();}
  writer.visitEnd();return writer.toByteArray();
 }
 public static void main(String[] args)throws Exception {
  var parent=SplitterComparison.class.getClassLoader();int checks=0,splits=0;
  try(var oldLoader=isolated(Path.of(args[0]),parent);
      var rebuiltLoader=isolated(Path.of(args[1]),parent)) {
   Method original=oldLoader.loadClass("emfjit.EvalSplitter").getMethod("split",byte[].class,int.class);
   Method rebuilt=rebuiltLoader.loadClass("emfjit.EvalSplitter").getMethod("split",byte[].class,int.class);
   for(int variant=0;variant<8;variant++)for(int count:new int[]{20,1800,2600})for(int budget:new int[]{1000,3000,6000,10000}) {
    byte[] input=model(variant,count);Object a=original.invoke(null,input,budget),b=rebuilt.invoke(null,input,budget);
    for(String field:new String[]{"split","originalCodeSize","chunks","maxChunkCodeSize","note","bytes"}) {
     Object x=a.getClass().getMethod(field).invoke(a),y=b.getClass().getMethod(field).invoke(b);
     boolean equal=x instanceof byte[] bytes?Arrays.equals(bytes,(byte[])y):Objects.equals(x,y);
     if(!equal)throw new AssertionError("variant="+variant+", stores="+count+", budget="+budget+", field="+field);
    }
    if((boolean)a.getClass().getMethod("split").invoke(a))splits++;checks++;
   }
  }
  System.out.println("PASS "+checks+" differential splitter cases; "+splits+" split results; generated bytes and fallback metadata identical.");
 }
}
